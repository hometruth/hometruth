/** The canonical local page for a schema document identified by a URI. */
export function schemaPagePath(schemaId: string): string | undefined {
  try {
    const path = new URL(schemaId).pathname;
    return path.startsWith("/schemas/") && path !== "/schemas/" ? path : undefined;
  } catch {
    return undefined;
  }
}

/** The catalog entry's title and page for a schema a device or sensor declares itself an instance of. */
export function schemaLink(schemaId: string): { title: string; page: string } | undefined {
  const entry = schemaCatalogEntries.find(candidate => candidate.schema.$id === schemaId);
  const page = entry && schemaPagePath(schemaId);
  return entry && page ? { title: entry.title, page } : undefined;
}

/**
 * The capability kind a schema is exposed as under `homeTruthObjectSchema.capabilities`,
 * derived from that schema's own property map rather than duplicated here, so a
 * device's `capabilities` array can be matched back to the schema it documents.
 */
export const CAPABILITY_KIND_SCHEMA_IDS: Readonly<Record<string, string>> = Object.fromEntries(
  Object.entries(homeTruthObjectSchema.properties.capabilities.properties).map(([kind, ref]) => [kind, ref.$ref]),
);

export function buildSchemaCatalogResponse(): unknown {
  const counts = { business: 0, api: 0, system: 0 };
  const order = { business: 0, api: 1, system: 2 };
  const schemas = [...schemaCatalogEntries].sort((a, b) => order[a.category] - order[b.category]).map((entry) => {
    counts[entry.category] += 1;
    const schemaId = entry.schema.$id;
    const page = schemaPagePath(schemaId);
    return { ...entry, schemaId, ...(page ? { page } : {}) };
  });
  return { schemas, counts, generatedAt: new Date().toISOString() };
}
